"""Tiny deterministic synthetic micrographs with exact ground-truth masks.

These are *simulated* data for tests, demos and autonomous agents. They are not
scientific data and every generated folder says so in ``README.txt`` and
``classes.json`` notes. Images look loosely like etched Zr micrographs: a
textured bright matrix, dark elongated "hydride" platelets and small round
"pores". Each specimen has its own platelet orientation and brightness so that
leakage-safe grouping by specimen matters.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
from PIL import Image

from .atomic import write_bytes_atomic, write_json_atomic
from .classes import CLASSES_FILENAME, ClassMap, SegClass
from .imageio import encode_png

SYNTHETIC_CLASS_MAP = ClassMap(
    classes=(
        SegClass(0, "matrix", "#000000"),
        SegClass(1, "hydride", "#e6194b"),
        SegClass(2, "pore", "#4363d8"),
    ),
    mask_encoding="indexed",
)


@dataclass(frozen=True)
class SyntheticSpec:
    specimens: int = 5
    images_per_specimen: int = 4
    size: int = 96
    seed: int = 7
    with_pores: bool = True


def _smooth_noise(rng: np.random.Generator, size: int, cells: int) -> np.ndarray:
    coarse = rng.random((cells, cells), dtype=np.float32)
    img = Image.fromarray(coarse, mode="F").resize((size, size), Image.Resampling.BICUBIC)
    return np.asarray(img, dtype=np.float32)


def _segment_distance(yy: np.ndarray, xx: np.ndarray, p0: np.ndarray, p1: np.ndarray) -> np.ndarray:
    d = p1 - p0
    length2 = float(d @ d) or 1.0
    t = np.clip(((yy - p0[0]) * d[0] + (xx - p0[1]) * d[1]) / length2, 0.0, 1.0)
    py = p0[0] + t * d[0]
    px = p0[1] + t * d[1]
    return np.hypot(yy - py, xx - px)


def generate_sample(spec: SyntheticSpec, specimen: int, index: int) -> tuple[np.ndarray, np.ndarray]:
    """Return ``(image uint8 HxW, mask uint8 HxW)`` for one specimen/image index."""
    size = spec.size
    specimen_rng = np.random.default_rng([spec.seed, specimen])
    base_angle = specimen_rng.uniform(0, np.pi)
    brightness = specimen_rng.uniform(150, 185)
    rng = np.random.default_rng([spec.seed, specimen, index])

    yy, xx = np.mgrid[0:size, 0:size].astype(np.float32)
    mask = np.zeros((size, size), dtype=np.uint8)

    n_platelets = int(rng.integers(3, 7))
    for _ in range(n_platelets):
        angle = base_angle + rng.normal(0, 0.25)
        length = rng.uniform(0.25, 0.6) * size
        centre = rng.uniform(0.1, 0.9, size=2) * size
        half = 0.5 * length * np.array([np.sin(angle), np.cos(angle)], dtype=np.float32)
        width = rng.uniform(1.0, 2.2)
        dist = _segment_distance(yy, xx, centre - half, centre + half)
        mask[dist <= width] = 1

    if spec.with_pores:
        for _ in range(int(rng.integers(1, 4))):
            cy, cx = rng.uniform(0.1, 0.9, size=2) * size
            radius = rng.uniform(3.0, 5.5)
            mask[np.hypot(yy - cy, xx - cx) <= radius] = 2

    texture = _smooth_noise(rng, size, 6) * 30.0 - 15.0
    image = np.full((size, size), brightness, dtype=np.float32) + texture
    image[mask == 1] = rng.uniform(70, 90)
    image[mask == 2] = rng.uniform(15, 30)
    # Mild blur across boundaries (like optics) then sensor noise.
    blurred = np.asarray(Image.fromarray(image, mode="F").resize((size // 2, size // 2), Image.Resampling.BILINEAR)
                         .resize((size, size), Image.Resampling.BILINEAR), dtype=np.float32)
    image = 0.6 * image + 0.4 * blurred + rng.normal(0, 6.0, size=(size, size)).astype(np.float32)
    return np.clip(np.rint(image), 0, 255).astype(np.uint8), mask


README = """SYNTHETIC DATA - NOT REAL MICROGRAPHS
Generated by MicroSegWorkbench for demos and automated tests.
Specimens: {specimens}  Images per specimen: {per}  Size: {size}x{size}  Seed: {seed}

Files: <specimen>_<index>.png (micrograph) + <specimen>_<index>_mask.png (indexed mask)
Mask values: 0 = matrix, 1 = hydride, 2 = pore (see classes.json)
Images from the same specimen share a group (stem prefix before the first underscore).
"""


def write_synthetic_dataset(folder: Path, spec: SyntheticSpec = SyntheticSpec()) -> list[str]:
    """Write a synthetic pair folder (OnlineAnnotator ``hydride_pairs`` naming). Returns stems."""
    folder.mkdir(parents=True, exist_ok=True)
    stems: list[str] = []
    for s in range(spec.specimens):
        for i in range(spec.images_per_specimen):
            image, mask = generate_sample(spec, s, i)
            stem = f"S{s + 1:02d}_{i + 1:04d}"
            write_bytes_atomic(folder / f"{stem}.png", encode_png(image))
            write_bytes_atomic(folder / f"{stem}_mask.png", encode_png(mask))
            stems.append(stem)
    class_map = SYNTHETIC_CLASS_MAP if spec.with_pores else ClassMap(SYNTHETIC_CLASS_MAP.classes[:2])
    payload = class_map.to_dict()
    payload["notes"] = ["synthetic data generated for testing; not scientific measurements"]
    write_json_atomic(folder / CLASSES_FILENAME, payload)
    (folder / "README.txt").write_text(
        README.format(specimens=spec.specimens, per=spec.images_per_specimen, size=spec.size, seed=spec.seed),
        encoding="utf-8",
    )
    return stems
